// Builds lib/lightdive-v3/footprints.ts from docs/lightdive/FOOTPRINTS.json (zh-Hant, en, ko written by hand;
// zh-Hans from scripts/lightdive-hant2hans.mjs). Run after editing the JSON:
//   node scripts/lightdive-footprints.mjs
import fs from "node:fs";
import { toHans, T2S } from "./lightdive-hant2hans.mjs";

const src = JSON.parse(fs.readFileSync("docs/lightdive/FOOTPRINTS.json", "utf8"));
const seen = new Set();
for (const it of src.items) {
  const key = `${it.dest}-${it.n}`;
  if (seen.has(key)) throw new Error(`duplicate ${key}`);
  seen.add(key);
  for (const k of ["zh", "en", "ko"]) if (!it[k]?.trim()) throw new Error(`${key}: missing ${k}`);
  for (const word of ["戰力", "光塵", "召喚", "稀有度", "出發令"]) if (it.zh.includes(word)) throw new Error(`${key}: game term ${word}`);
}
if (seen.size !== 48) throw new Error(`expected 48 fragments, got ${seen.size}`);
const items = src.items.map((it) => ({ dest: it.dest, n: it.n, text: { "zh-Hant": it.zh, "zh-Hans": toHans(it.zh), en: it.en, ko: it.ko } }));
const out = `// Generated by scripts/lightdive-footprints.mjs from docs/lightdive/FOOTPRINTS.json. Do not edit by hand.
// 足跡: two story fragments per destination. The first opens with the first result collected there, the second with
// the ${src.unlock[1]}th.
import type { Locale } from "@/lib/translations";

export const FOOTPRINT_UNLOCK = ${JSON.stringify(src.unlock)} as const;
export type Footprint = { dest: number; n: 1 | 2; text: Record<Locale, string> };
export const FOOTPRINTS: Footprint[] = ${JSON.stringify(items, null, 1)};
`;
fs.writeFileSync("lib/lightdive-v3/footprints.ts", out);
const unmapped = [...new Set([...src.items.map((i) => i.zh).join("")])].filter((c) => /[\u4e00-\u9fff]/.test(c) && !T2S.has(c) && toHans(c) === c);
console.log(`wrote lib/lightdive-v3/footprints.ts (${items.length} fragments)`);
void unmapped;
