// Extracts the game-icons.net icons Lightdive uses into components/lightdive/game/icons.ts.
// game-icons.net icons are by Lorc, Delapouite and contributors, licensed CC BY 3.0.
//   node scripts/lightdive-icons.mjs
import fs from "node:fs";

const PICK = {
  overview: "radar-sweep",
  expedition: "star-formation",
  fleets: "orbital",
  spires: "obelisk",
  seekers: "astronaut-helmet",
  prisms: "prism",
  summon: "magic-portal",
  market: "trade",
  treasury: "open-treasure-chest",
  codex: "open-book",
  guide: "help",
  rvyn: "coins",
  lightdust: "crystal-shine",
  pool: "sunbeams",
  signal: "aerial-signal",
  clock: "sundial",
  luminance: "sun-radiations",
  voyage: "compass",
  launch: "beam-satellite",
  claim: "coins-pile",
  settle: "scroll-unfurled",
  crystal: "crystal-growth",
  settings: "cog",
};
const set = JSON.parse(fs.readFileSync("node_modules/@iconify-json/game-icons/icons.json", "utf8"));
const out = {};
for (const [key, name] of Object.entries(PICK)) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`missing icon ${name}`);
  out[key] = icon.body;
}
const body = `// Generated by scripts/lightdive-icons.mjs. Do not edit by hand.
// Icons from game-icons.net by Lorc, Delapouite and contributors, licensed CC BY 3.0
// (https://creativecommons.org/licenses/by/3.0/). Credited on the game's "How to play" page.
export const ICON_PATHS = ${JSON.stringify(out, null, 2)} as const;
export type IconName = keyof typeof ICON_PATHS;
`;
fs.writeFileSync("components/lightdive/game/icons.ts", body);
console.log(`wrote ${Object.keys(out).length} icons`);
