// Builds lib/lightdive-v3/story.ts from docs/lightdive/STORY-v2.md (the novel shown on the game's 故事 page) and its
// translations STORY-v2.en.md and STORY-v2.ko.md. Simplified Chinese is converted from the Traditional text.
// Every translation must have the same volumes, chapters and paragraphs, so bookmarks and the centred lines (worked
// out from the Traditional text) line up in every language.
// Run: node scripts/lightdive-v3-story.mjs
import fs from "node:fs";
import { toHans } from "./lightdive-hant2hans.mjs";

const TITLES = { "zh-Hant": "潛光紀", "zh-Hans": "潜光纪", en: "Chronicles of the Dive", ko: "잠광기" };

// "# " starts a volume, "## " a chapter; every other non-empty line is a paragraph.
function parse(text, name) {
  const volumes = [];
  for (const l of text.split(/\r?\n/)) {
    if (l.startsWith("# ")) { volumes.push({ title: l.slice(2).trim(), chapters: [] }); continue; }
    if (l.startsWith("## ")) { volumes.at(-1).chapters.push({ title: l.slice(3).trim(), paras: [] }); continue; }
    const v = volumes.at(-1);
    if (!v?.chapters.length || !l.trim() || l.startsWith(">")) continue;
    v.chapters.at(-1).paras.push(l.trim());
  }
  if (!volumes.length || volumes.some((v) => v.chapters.some((c) => !c.paras.length))) throw new Error(`${name}: empty chapter`);
  return volumes;
}
const shape = (volumes) => volumes.map((v) => v.chapters.map((c) => c.paras.length).join(",")).join(" | ");

const source = fs.readFileSync("docs/lightdive/STORY-v2.md", "utf8");
const zh = parse(source, "zh-Hant");
const out = { "zh-Hant": { title: TITLES["zh-Hant"], volumes: zh }, "zh-Hans": { title: TITLES["zh-Hans"], volumes: parse(toHans(source), "zh-Hans") } };
for (const locale of ["en", "ko"]) {
  const volumes = parse(fs.readFileSync(`docs/lightdive/STORY-v2.${locale}.md`, "utf8"), locale);
  if (shape(volumes) !== shape(zh)) throw new Error(`${locale}: paragraphs do not match the Traditional text\n  ${shape(volumes)}\n  ${shape(zh)}`);
  out[locale] = { title: TITLES[locale], volumes };
}
// The motto and the end-of-volume lines are centred: [chapter index across all volumes, paragraph index].
const centre = zh.flatMap((v) => v.chapters).flatMap((c, ci) => c.paras.flatMap((p, pi) => (p.startsWith("「潛進深空") || p.startsWith("——") ? [[ci, pi]] : [])));

const chapters = zh.flatMap((v) => v.chapters);
const chars = chapters.reduce((a, c) => a + c.paras.join("").length, 0);
// One module per language, so the game only downloads the one being read.
fs.mkdirSync("lib/lightdive-v3/story", { recursive: true });
for (const [locale, story] of Object.entries(out)) {
  fs.writeFileSync(`lib/lightdive-v3/story/${locale}.ts`, `// Generated by scripts/lightdive-v3-story.mjs. Edit docs/lightdive/STORY-v2*.md, then re-run.
import type { Story } from "../story";
export const STORY: Story = ${JSON.stringify(story, null, 1)};
`);
}
fs.writeFileSync("lib/lightdive-v3/story.ts", `// Generated by scripts/lightdive-v3-story.mjs from docs/lightdive/STORY-v2*.md. Edit the documents, then re-run.
// The text of each language lives in ./story/<locale>.ts and is loaded when the Story page opens.
import type { Locale } from "@/lib/translations";
export type Story = { title: string; volumes: { title: string; chapters: { title: string; paras: string[] }[] }[] };
/** Chapters in the novel; the same in every language. */
export const CHAPTERS = ${chapters.length};
/** Centred paragraphs, as [chapter index across all volumes, paragraph index]; the same in every language. */
export const CENTRED: readonly (readonly [number, number])[] = ${JSON.stringify(centre)};
export function loadStory(locale: Locale): Promise<Story> {
  switch (locale) {
    case "en": return import("./story/en").then((m) => m.STORY);
    case "zh-Hans": return import("./story/zh-Hans").then((m) => m.STORY);
    case "ko": return import("./story/ko").then((m) => m.STORY);
    default: return import("./story/zh-Hant").then((m) => m.STORY);
  }
}
`);
console.log(`story.ts written: 4 languages, ${zh.length} volumes, ${chapters.length} chapters, ${chars} characters in Traditional Chinese, ${centre.length} centred lines`);
