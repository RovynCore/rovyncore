// Builds lib/lightdive-v3/whitepaper.ts from docs/lightdive/WHITEPAPER-v3.md (the game's 白皮書 page) and its
// translations WHITEPAPER-v3.en.md and WHITEPAPER-v3.ko.md. Simplified Chinese is converted from the Traditional text.
// "## " starts a section, "### " a subheading, "- " a list item, "| " a table row; other lines are paragraphs.
// Every translation must have the same sections, blocks, list items and table rows as the Traditional text.
// Run: node scripts/lightdive-v3-whitepaper.mjs
import fs from "node:fs";
import { toHans } from "./lightdive-hant2hans.mjs";

const cells = (l) => l.trim().replace(/^\||\|$/g, "").split("|").map((c) => c.trim());
function parse(text, name) {
  const md = text.split(/\r?\n/);
  const title = md.find((l) => l.startsWith("# "))?.slice(2).trim() ?? "白皮書";
  const sections = [];
  for (const l of md) {
    if (l.startsWith("## ")) { sections.push({ title: l.slice(3).trim(), blocks: [] }); continue; }
    const s = sections.at(-1);
    if (!s || !l.trim() || l.startsWith(">") || l.startsWith("# ")) continue;
    const last = s.blocks.at(-1);
    if (l.startsWith("### ")) s.blocks.push({ t: "h3", text: l.slice(4).trim() });
    else if (l.startsWith("- ")) {
      if (last?.t === "ul") last.items.push(l.slice(2).trim());
      else s.blocks.push({ t: "ul", items: [l.slice(2).trim()] });
    } else if (l.trim().startsWith("|")) {
      if (/^\|[\s|:-]+\|$/.test(l.trim())) continue; // the separator row
      if (last?.t === "table") last.rows.push(cells(l));
      else s.blocks.push({ t: "table", head: cells(l), rows: [] });
    } else s.blocks.push({ t: "p", text: l.trim() });
  }
  if (!sections.length || sections.some((s) => !s.blocks.length)) throw new Error(`${name}: empty section`);
  return { title, sections };
}

/** "p,h3,ul3,table6x4" per section — two documents must have the same shape. */
const shape = (wp) => wp.sections.map((s) => s.blocks.map((b) => (b.t === "ul" ? `ul${b.items.length}` : b.t === "table" ? `table${b.rows.length}x${b.head.length}` : b.t)).join(","));

const source = fs.readFileSync("docs/lightdive/WHITEPAPER-v3.md", "utf8");
const out = { "zh-Hant": parse(source, "zh-Hant"), "zh-Hans": parse(toHans(source), "zh-Hans") };
const want = shape(out["zh-Hant"]);
for (const locale of ["en", "ko"]) {
  const wp = parse(fs.readFileSync(`docs/lightdive/WHITEPAPER-v3.${locale}.md`, "utf8"), locale);
  const got = shape(wp);
  if (got.length !== want.length) throw new Error(`${locale}: ${got.length} sections, expected ${want.length}`);
  got.forEach((g, i) => { if (g !== want[i]) throw new Error(`${locale}: section ${i + 1} is "${g}", expected "${want[i]}"`); });
  out[locale] = wp;
}
fs.writeFileSync("lib/lightdive-v3/whitepaper.ts", `// Generated by scripts/lightdive-v3-whitepaper.mjs from docs/lightdive/WHITEPAPER-v3*.md. Edit the documents, then re-run.
import type { Locale } from "@/lib/translations";
export type WpBlock = { t: "p" | "h3"; text: string } | { t: "ul"; items: string[] } | { t: "table"; head: string[]; rows: string[][] };
export type Wp = { title: string; sections: { title: string; blocks: WpBlock[] }[] };
export const WHITEPAPERS: Record<Locale, Wp> = ${JSON.stringify(out, null, 1)};
`);
const zh = out["zh-Hant"];
console.log(`whitepaper.ts written: 4 languages, ${zh.sections.length} sections, ${zh.sections.reduce((a, s) => a + s.blocks.length, 0)} blocks each`);
