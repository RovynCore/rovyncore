"""Charts and the comparison report (sim-v3.cjs reference vs this model). Differences are reported, never tuned away."""
from __future__ import annotations

import csv
import statistics

from .params import ROOT

# sim-v3.cjs (method B), 5 runs each, recorded 2026-10-10 in the round 1 report, section 6. Day 365 unless noted.
SIM_V3 = {
    "base": {"pool": (981_450, 988_694), "rate_d90": (0.00538, 0.00543), "rate_d365": (0.00460, 0.00469), "received_over_spent": (0.71, 0.71), "teams_d365": (2999, 3000)},
    "boom": {"pool": (978_806, 989_397), "rate_d90": (0.00540, 0.00552), "rate_d365": (0.00464, 0.00466), "received_over_spent": (0.71, 0.71), "teams_d365": (3000, 3000)},
    "bust": {"pool": (530_341, 534_393), "rate_d90": (0.00646, 0.00662), "rate_d365": (0.00512, 0.00520), "received_over_spent": (0.89, 0.89), "teams_d365": (1453, 1467)},
}


def _rows(scenario: str) -> list[dict]:
    with (ROOT / "reports" / scenario / "daily.csv").open(encoding="utf-8") as f:
        return [{k: float(v) for k, v in r.items()} for r in csv.DictReader(f)]


def charts(scenarios: list[str]) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(2, 2, figsize=(11, 7))
    panels = [("pool_balance", "Core Light Pool (RVYN)"), ("rate", "Rate (RVYN per point)"), ("players_active", "Active players"), ("yield_ratio", "Perceived return ratio")]
    for ax, (key, title) in zip(axes.flat, panels):
        for s in scenarios:
            rows = _rows(s)
            ax.plot([r["day"] for r in rows], [r[key] for r in rows], label=s, linewidth=1)
        ax.set_title(title)
        ax.grid(alpha=0.3)
    axes[0][0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(ROOT / "reports" / "overview.png", dpi=120)
    plt.close(fig)


def _metrics(summary: dict, rows: list[dict]) -> dict:
    pl = summary["players"]
    return {
        "pool": summary["final_day"]["pool_balance"],
        "rate_d90": rows[89]["rate"] if len(rows) >= 90 else float("nan"),
        "rate_d365": summary["final_day"]["rate"],
        "received_over_spent": (pl["received_total"] + pl["unclaimed_credit"]) / pl["spent_total"] if pl else float("nan"),
        "teams_d365": summary["final_day"]["players_active"],
    }


def comparison_report(results: dict, spread: dict) -> None:
    lines = ["# Round 1 results: Python model vs sim-v3.cjs", "",
             "Generated by `python -m lightdive_sim all`. Every number below comes from an actual run; nothing was tuned to match.", "",
             "## Main scenarios (seed from config) and the seed spread", "",
             "| scenario | metric | sim-v3 range | this model | spread over seeds | difference vs sim-v3 midpoint |",
             "|---|---|---|---|---|---|"]
    for s in ("base", "boom", "bust"):
        m = _metrics(results[s], _rows(s))
        sp = [_metrics(x, list(csv.DictReader((ROOT / "reports" / "_spread" / f"{s}-{i}" / "daily.csv").open(encoding="utf-8"))))
              for i, x in enumerate(spread[s])]
        for key, (lo, hi) in SIM_V3[s].items():
            mid = (lo + hi) / 2
            vals = [float(x[key]) for x in sp]
            diff = (m[key] - mid) / mid * 100 if mid else float("nan")
            lines.append(f"| {s} | {key} | {lo:,} – {hi:,} | {m[key]:,.5g} | {min(vals):,.5g} – {max(vals):,.5g} | {diff:+.1f}% |")
    lines += ["", "## All scenarios", "",
              "| scenario | days | pool day 365 | rate day 365 | active players | blocked dives | rejected newcomers | pool shortfall | ROI p10 / p50 / p90 | share ROI ≥ 1 | invariants |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s, r in results.items():
        f, pl = r["final_day"], r["players"]
        roi = f"{pl['roi_p10']:.2f} / {pl['roi_p50']:.2f} / {pl['roi_p90']:.2f}" if pl else "-"
        share = f"{pl['share_roi_at_least_1']:.0%}" if pl else "-"
        lines.append(f"| {s} | {r['days_run']} | {f.get('pool_balance', 0):,.0f} | {f.get('rate', 0):.5f} | {f.get('players_active', 0)} | "
                     f"{r['blocked_dives_total']:,} on {r['days_with_blocked_dives']} days | {r['rejected_players_total']:,} | {r['pool_shortfall_rvyn']:,.2f} | {roi} | {share} | "
                     f"{'FAIL: ' + r['invariant_failure'] if r['invariant_failure'] else 'all passed'} |")
    lines += ["", "ROI = (claimed + unclaimed credit + market sales) / RVYN paid into the game, per player who paid anything.",
              "Output hashes and configs are in each `reports/<scenario>/summary.json`."]
    (ROOT / "reports" / "comparison.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def spread_stats(values: list[float]) -> tuple[float, float]:
    return statistics.mean(values), statistics.pstdev(values)


def sweep_report(scenario: str, key: str, runs: dict, out_dir) -> None:
    """One setting varied over values (several seeds each): a table of day-365 results and a chart of the first seed."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    def metrics(r: dict) -> dict:
        f, pl, m = r["final_day"], r["players"], r["market"]
        return {
            "pool": f["pool_balance"], "active": f["players_active"], "idle_spires": f["idle_spires"], "listed_spires": f["listed_spires"],
            "rejected": r["rejected_players_total"], "trades": m["trades"], "volume": m["volume_rvyn"],
            "sellers": m["sellers"] or 0, "walked_away": m["walked_away"] or 0, "delisted": m["delisted"] or 0,
            "ratio": (pl["received_total"] + pl["unclaimed_credit"]) / pl["spent_total"] if pl else float("nan"),
            "roi_p50": pl.get("roi_p50", float("nan")), "roi_ge_1": pl.get("share_roi_at_least_1", float("nan")),
            "failed": bool(r["invariant_failure"]),
        }

    def cell(vals: list[float], fmt: str) -> str:
        lo, hi, mean = min(vals), max(vals), sum(vals) / len(vals)
        return format(mean, fmt) if lo == hi else f"{format(mean, fmt)} ({format(lo, fmt)}–{format(hi, fmt)})"

    cols = [("pool", "pool day 365", ",.0f"), ("active", "active players", ",.0f"), ("idle_spires", "idle spires", ",.0f"),
            ("listed_spires", "of which listed", ",.0f"), ("rejected", "rejected newcomers", ",.0f"), ("trades", "market trades", ",.0f"),
            ("volume", "market volume RVYN", ",.0f"), ("sellers", "sellers", ",.0f"), ("walked_away", "walked away", ",.0f"),
            ("delisted", "gave up", ",.0f"), ("ratio", "taken out / put in", ".2f"), ("roi_p50", "ROI p50", ".2f"), ("roi_ge_1", "ROI ≥ 1", ".0%")]
    lines = [f"# Sweep: {key} on scenario {scenario}", "",
             f"Generated by `python -m lightdive_sim sweep {scenario} --key {key}`. Mean over {len(next(iter(runs.values())))} seeds, "
             "range in brackets. Every number comes from an actual run.", "",
             "| " + key.split(".")[-1] + " | " + " | ".join(c[1] for c in cols) + " | invariants |",
             "|" + "---|" * (len(cols) + 2)]
    table = {}
    for v, rs in runs.items():
        ms = [metrics(r) for r in rs]
        table[v] = ms
        lines.append(f"| {v:g} | " + " | ".join(cell([m[c] for m in ms], fmt) for c, _, fmt in cols) + " | "
                     + ("FAIL" if any(m["failed"] for m in ms) else "all passed") + " |")
    lines += ["", "idle spires = spires alive but on no team and not docked (listed ones included). sellers / walked away = quitting "
              "players with cards who listed them / did not. gave up = listings withdrawn unsold after delist_after_days."]
    (out_dir / "sweep.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (out_dir / "sweep.json").write_text(__import__("json").dumps({str(k): v for k, v in table.items()}, indent=1), encoding="utf-8")

    fig, axes = plt.subplots(2, 2, figsize=(11, 7))
    panels = [("pool_balance", "Core Light Pool (RVYN)"), ("players_active", "Active players"), ("idle_spires", "Idle spires"),
              ("rejected_players", "Rejected newcomers (cumulative)")]
    for ax, (k, title) in zip(axes.flat, panels):
        for v in runs:
            with (out_dir / f"{v:g}-s0" / "daily.csv").open(encoding="utf-8") as f:
                rows = [{a: float(b) for a, b in r.items()} for r in csv.DictReader(f)]
            ys = [r[k] for r in rows]
            if k == "rejected_players":
                acc = 0.0
                ys = [acc := acc + y for y in ys]
            ax.plot([r["day"] for r in rows], ys, label=f"{key.split('.')[-1]} = {v:g}", linewidth=1)
        ax.set_title(title)
        ax.grid(alpha=0.3)
    axes[0][0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(out_dir / "sweep.png", dpi=120)
    plt.close(fig)
